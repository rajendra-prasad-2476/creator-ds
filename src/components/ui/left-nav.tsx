/* ─── Types ─── */
export type NavItemDef = {
  id: string
  label: string
  icon: React.ReactNode
  active?: boolean
  onClick?: () => void
}

export type NavSectionDef = {
  id: string
  label: string
  items: NavItemDef[]
}

/* ─── NavItem ─── */
function NavItem({ item }: { item: NavItemDef }) {
  return (
    <button
      type="button"
      onClick={item.onClick}
      data-active={item.active || undefined}
      className={cn(
        "group relative flex w-full flex-col items-start pl-[30px] pr-3 py-3 text-left outline-none transition-colors",
        item.active
          ? "bg-[#e7edfe]"
          : "bg-[var(--cds-primary-surface-subtle,#f5f8fe)] hover:bg-[#e7edfe]/60"
      )}
    >
      {item.active && <ActiveIndicator />}
      <div className="flex items-center gap-3">
        <span
          className={cn(
            "shrink-0",
            item.active
              ? "text-[var(--cds-primary-surface-default,#0D4EF2)]"
              : "text-[var(--cds-neutral-text-dark,#25272C)]"
          )}
        >
          {item.icon}
        </span>
        <span
          className="text-[14px] leading-[18px] text-[var(--cds-neutral-text-dark,#25272C)] whitespace-nowrap"
          style={{ fontFamily: "'Zoho Puvi', Lato, sans-serif", fontWeight: item.active ? 600 : 400 }}
        >
          {item.label}
        </span>
      </div>
    </button>
  )
}

/* ─── NavSection ─── */
function NavSection({ section }: { section: NavSectionDef }) {
  return (
    <div className="flex w-full flex-col">
      {/* Section header */}
      <div className="flex items-center bg-[var(--cds-primary-surface-subtle,#f5f8fe)] pl-[30px] pr-[10px] py-[10px]">
        <span
          className="text-[12px] leading-normal whitespace-nowrap text-[var(--cds-neutral-text-default,#6C6D71)]"
          style={{ fontFamily: "'Zoho Puvi', Lato, sans-serif", fontWeight: 700 }}
        >
          {section.label}
        </span>
      </div>
      {/* Nav items */}
      {section.items.map((item) => (
        <NavItem key={item.id} item={item} />
      ))}
    </div>
  )
}

